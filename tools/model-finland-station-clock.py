"""Blender authoring source for the 5.5 m Mobatime dial facing Lenin Square.

blender -b -P tools/model-finland-station-clock.py
Dimensions and installation photographs: https://mobatime.ru/product/fasadnye-chasy-finlyandskij-vokzal-g-sankt-peterburg/
"""
import math
from pathlib import Path

import bpy
import bmesh


def machined_solid(rings):
    """Closed metal pressing; depth runs towards the square."""
    width = len(rings[0])
    faces = [tuple(range(width))]
    for n in range(len(rings) - 1):
        for i in range(width):
            j = (i + 1) % width
            a = n * width
            faces.append((a + i, a + j, a + width + j, a + width + i))
    faces.append(tuple(range(len(rings) * width - width, len(rings) * width)))
    mesh = bpy.data.meshes.new("clock pressing")
    mesh.from_pydata([(x, -depth, y) for ring in rings for x, y, depth in ring], [], faces)
    bm = bmesh.new()
    bm.from_mesh(mesh)
    bmesh.ops.recalc_face_normals(bm, faces=list(bm.faces))
    bmesh.ops.triangulate(bm, faces=list(bm.faces))
    bm.to_mesh(mesh)
    bm.free()
    mesh.update()
    return mesh


def turned(profile, segments):
    return machined_solid([
        [(r * math.sin(i * math.tau / segments), r * math.cos(i * math.tau / segments), depth)
         for i in range(segments)] for r, depth in profile
    ])


def blade(outline, angle, first, last):
    s, c = math.sin(angle), math.cos(angle)
    return machined_solid([[(c*x + s*y, -s*x + c*y, depth) for x, y in outline]
                           for depth in (first, last)])


def pack(meshes):
    vertices, indices = [], []
    for mesh in meshes:
        lookup = {}
        for face in mesh.polygons:
            for i in face.vertices:
                # Split sharp faces so each bevel keeps its own highlight.
                key = (i, tuple(round(n, 4) for n in face.normal))
                if key not in lookup:
                    lookup[key] = len(vertices) // 3
                    x, y, z = mesh.vertices[i].co
                    vertices.extend(round(q * 1000) for q in (x, z, -y))
                indices.append(lookup[key])
        bpy.data.meshes.remove(mesh)
    return [vertices, indices]


# Aluminium return and chamfer, charcoal dial, raised white rectangular indices.
# Dusk photograph finbahn_02 shows the broad counterweighted hour hand and
# longer minute blade. Use the same static indicated time as the prior model.
parts = {
    "rim": pack([turned([(2.68, 0), (2.75, .06), (2.75, .19), (2.69, .225)], 56)]),
    "dial": pack([turned([(2.64, .226), (2.67, .235), (2.64, .25)], 56)]),
    "indices": pack([blade([(-.09, 1.95), (.09, 1.95), (.09, 2.47), (-.09, 2.47)],
                            i * math.tau / 12, .252, .287) for i in range(12)]),
    "hands": pack([
        blade([(-.12, -.32), (.12, -.32), (.115, 1.04), (.055, 1.58), (-.055, 1.58), (-.115, 1.04)],
              math.radians(-52), .32, .36),
        blade([(-.065, -.4), (.065, -.4), (.08, 1.46), (.035, 2.24), (-.035, 2.24), (-.08, 1.46)],
              math.radians(116), .37, .41),
        turned([(.15, .41), (.15, .43), (.10, .455)], 12),
    ]),
}
dest = Path(__file__).resolve().parents[1] / "src/world/landmarksFinlyandskyStation/clock-mesh.js"
out = "// Generated by Blender with tools/model-finland-station-clock.py. Local XYZ in millimetres.\n"
out += "export const clockMesh = {\n"
for name, pair in parts.items():
    out += "  " + name + ": [\n"
    for data in pair:
        out += "    [\n" + "\n".join("      " + ",".join(map(str, data[i:i+36])) + "," for i in range(0,len(data),36)) + "\n    ],\n"
    out += "  ],\n"
out += "};\n"
dest.write_text(out, encoding="utf-8", newline="\n")
print("Station clock triangles:", {k:len(pair[1])//3 for k,pair in parts.items()})
