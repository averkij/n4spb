// Extract the surveyed right-bank reach; run through tools/area.mjs finlyandsky.
// The two anchors distinguish this bank from the opposite Smolny shoreline.
import fs from 'node:fs';
import { waterGeo } from '../src/world/environment/waterways.js';
const bank=waterGeo().banks.find(b=>b.key==='neva'&&b.pts.some(p=>Math.hypot(p[0]-1162.6,p[1]+2408)<2)&&b.pts.some(p=>p[0]>2700&&p[0]<2800&&p[1]<-2850));
if(!bank)throw Error('Mapped Sverdlovskaya bank anchors absent');
const start=bank.pts.findIndex(p=>p[0]>=1160),end=bank.pts.findIndex((p,i)=>i>start&&p[0]>=2910);
if(start<0||end<0)throw Error('Mapped bank direction changed');
const line=bank.pts.slice(start,end+1);
fs.writeFileSync('src/areas/finlyandsky/bank-line.js',`// Surveyed Neva right-bank line, generated by tools/prepare-finlyandsky-banks.mjs.\n// OpenStreetMap contributors, ODbL; same snapshot as data/city.js.\nexport const BANK_LINE=${JSON.stringify(line)};\n`);
console.log(`Saved ${line.length} right-bank vertices.`);
