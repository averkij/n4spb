// Keep the area's pure layout contract independent of renderer dependencies.
// node tools/area.mjs moskovskaya tools/moskovskaya-square-paving-data.mjs [--check]
import assert from 'node:assert/strict';
import fs from 'node:fs';
import { MOSCOW_SQUARE_PAVED_RINGS } from '../src/world/landmarksMoskovskaya/soviets-square-plan.js';

assert.equal(process.env.AREA, 'moskovskaya', 'run through tools/area.mjs moskovskaya');
const target = new URL('../src/areas/moskovskaya/data/soviets-square-paving.js', import.meta.url);
const text = '// GENERATED by tools/area.mjs moskovskaya tools/moskovskaya-square-paving-data.mjs.\n'
  + '// Exact surveyed paving, excluding mapped lawns and all eleven fountain basins.\n'
  + 'export const MOSCOW_SQUARE_PAVED_RINGS = JSON.parse(' + JSON.stringify(JSON.stringify(MOSCOW_SQUARE_PAVED_RINGS)) + ');\n';
if (process.argv.includes('--check')) assert.equal(fs.readFileSync(target, 'utf8').replaceAll('\r\n', '\n'), text, 'regenerate Moscow Square paving data');
else fs.writeFileSync(target, text);
console.log(`${process.argv.includes('--check') ? 'Verified' : 'Generated'} ${MOSCOW_SQUARE_PAVED_RINGS.length} pure Moscow Square paving rings`);
