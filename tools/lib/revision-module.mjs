// The generated map of bake revisions (src/core/baked-revision.js): one revision per live area, written ONLY by renderRevisionModule(map) - from tools/lib/bake-publish.mjs (after a bake) and
// tools/baked-revision-sync.mjs (repair). tools/bake-manifest-check.mjs requires the file to equal render(map from the manifests), byte for byte, so a hand edit cannot go unnoticed.
//   renderRevisionModule(map)      the module text (one entry per line, alphabetical, ends with a newline)
//   parseRevisionModule(text)      the map back, or null when the text is not a generated per-area module (the legacy single constant, a hand edit that broke the shape)
//   readRevisionMap(root)          parseRevisionModule of root/src/core/baked-revision.js (null when absent or not parseable)
//   readManifest(dir)              { manifest, error } of dir/manifest.json
//   mapFromManifests(root, rows)   { id: revision } of the live rows that carry a valid manifest of the current scheme
// Pure Node, no node_modules.
import fs from 'node:fs';
import path from 'node:path';
import { BAKE_SCHEME } from '../baked-revision.mjs';

export const REVISION_FILE = 'src/core/baked-revision.js';
const HEADER = '// Generated by tools/lib/bake-publish.mjs / tools/baked-revision-sync.mjs. Do not edit. One bake revision per live area.';
const REV_RE = /^[0-9a-f]{20}$/;
const ID_RE = /^[A-Za-z][A-Za-z0-9_-]*$/;
const keyText = (id) => (/^[A-Za-z_$][\w$]*$/.test(id) ? id : JSON.stringify(id));

export function renderRevisionModule(map) {
  const ids = Object.keys(map).sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
  for (const id of ids) {
    if (!ID_RE.test(id)) throw new Error(`renderRevisionModule: bad area id ${JSON.stringify(id)}`);
    if (typeof map[id] !== 'string' || !REV_RE.test(map[id])) throw new Error(`renderRevisionModule: the revision of ${id} is not 20 hex digits (${JSON.stringify(map[id])})`);
  }
  return `${HEADER}
export const BAKED_REVISIONS = {
${ids.map((id) => `  ${keyText(id)}: '${map[id]}',\n`).join('')}};
const AREA = typeof document !== 'undefined' ? document.documentElement.dataset.area : undefined;
/** the revision of THIS page's area; 'none' for an unknown or parked area, which never matches a manifest */
export const BAKED_REVISION = (AREA && BAKED_REVISIONS[AREA]) || 'none';
`;
}

/** the map of a generated module, or null. Strict: only the shape that renderRevisionModule writes parses (the check compares the text as well). */
export function parseRevisionModule(text) {
  const m = /^[^\n]*\nexport const BAKED_REVISIONS = \{\n((?:  [^\n]*\n)*)\};\n/.exec(text);
  if (!m) return null;
  const map = {};
  for (const line of m[1].split('\n').filter(Boolean)) {
    const e = /^  (?:([A-Za-z_$][\w$]*)|"([^"\\]+)"): '([0-9a-f]{20})',$/.exec(line);
    if (!e) return null;
    const id = e[1] ?? e[2]; if (Object.prototype.hasOwnProperty.call(map, id)) return null;
    map[id] = e[3];
  }
  return map;
}
export function readRevisionMap(root) {
  let text; try { text = fs.readFileSync(path.join(root, REVISION_FILE), 'utf8'); } catch { return null; }
  return parseRevisionModule(text);
}
export function readRevisionModuleText(root) {
  try { return fs.readFileSync(path.join(root, REVISION_FILE), 'utf8'); } catch { return null; }
}

export const areaDir = (root, row) => path.join(root, 'assets', row.bake);
export function readManifest(dir) {
  const f = path.join(dir, 'manifest.json');
  if (!fs.existsSync(f)) return { manifest: null, error: null };
  try { return { manifest: JSON.parse(fs.readFileSync(f, 'utf8')), error: null }; } catch (e) { return { manifest: null, error: `manifest.json is not JSON (${e.message})` }; }
}
/** a manifest that may contribute its revision to the map: current scheme, format 1, the area of its row, a 20-hex revision */
export function manifestUsable(manifest, row) {
  return !!manifest && manifest.format === 1 && manifest.scheme === BAKE_SCHEME && manifest.area === row.id && typeof manifest.revision === 'string' && REV_RE.test(manifest.revision);
}
export const isLiveRow = (row) => !row.parked && row.status !== 'planned';
/** { id: manifest } for the rows that have one (parsed), and { id: error } for the unreadable */
export function readManifests(root, rows) {
  const manifests = {}, errors = {};
  for (const row of rows) { const { manifest, error } = readManifest(areaDir(root, row)); if (manifest) manifests[row.id] = manifest; if (error) errors[row.id] = error; }
  return { manifests, errors };
}
/** { id: revision } of the live rows whose manifest is usable */
export function mapFromManifests(root, rows) {
  const map = {};
  for (const row of rows.filter(isLiveRow)) { const { manifest } = readManifest(areaDir(root, row)); if (manifestUsable(manifest, row)) map[row.id] = manifest.revision; }
  return map;
}
