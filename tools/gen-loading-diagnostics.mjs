// Diagnostic entry points derived from every live area page.
// They run the SAME scene modules/bake after Start or an intentional hand-off.
// They are not registry areas and never author/bake scene data.
import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
import { VERSION } from '../src/core/version.js';
import { REGISTRY } from '../src/areas/registry.js';
import { handoffPage } from '../src/core/handoff.js';

const root = fileURLToPath(new URL('../', import.meta.url));
for (const area of Object.values(REGISTRY).filter(a => !a.parked && a.status !== 'planned')) {
  const source = fs.readFileSync(path.join(root, area.page), 'utf8').replace(/\r\n/g, '\n');
  const main = '<script type="module" src="./src/menu/entry.js"></script>';
  assert.equal(source.split(main).length, 2, 'one landing-page main script required');
  assert.equal(source.split('<head>').length, 2, 'one head required');
  assert.equal(source.split('<meta charset="utf-8">').length, 2, 'one charset meta required');
  const output = source
    .replace(/(<script type="importmap">)([^]*?)(<\/script>)/, (_, start, json, end) => {
      const map = JSON.parse(json);
      // The adapter imports the original modules outside this importer scope.
      // Other builders, game pages and bake closures are unchanged.
      map.scopes = { ...map.scopes, './src/main.js': {
        ...map.scopes?.['./src/main.js'],
        ...Object.fromEntries(['batch2', 'spatial', 'fixture-cells', 'compact-static', 'ndproxy']
          .map(name => ['./src/core/' + name + '.js', './src/core/loading-finalize-diagnostics.js'])),
      } };
      return start + '\n' + JSON.stringify(map, null, 2) + '\n' + end;
    })
    .replace(/<!-- GENERATED[^]*?-->/, `<!-- GENERATED by tools/gen-loading-diagnostics.mjs from ${area.page}. Do not edit. -->`)
    .replace('<meta charset="utf-8">', `<meta charset="utf-8">\n<meta name="diagnostics-version" content="${VERSION}">\n<meta name="diagnostics-bake" content="${area.bake}">\n<script src="./src/core/loading-diagnostics.js"></script>`)
    .replace(/<title>[^]*?<\/title>/, '<title>Loading diagnostics · Saint Petersburg</title>')
    .replace(main, '<script id="diagnostic-main" type="text/plain" data-src="./src/menu/entry.js"></script>');
  const filename = handoffPage(area.page, 'diagscene=1');
  const target = path.join(root, filename);
  if (process.argv.includes('--check')) {
    assert.equal(fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n'), output,
      `${filename} is stale: run node tools/gen-loading-diagnostics.mjs`);
    console.log(`${filename} matches ${area.page}`);
  } else {
    fs.writeFileSync(target, output);
    console.log(`Generated ${filename}`);
  }
}
