// Standalone diagnostic entry point, derived from the current landing page.
// It runs the SAME scene modules/bake, after explicit Start, with an early recorder.
// It is not a registry area and is never used to author/bake scene data.
import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
import { VERSION } from '../src/core/version.js';

const root = fileURLToPath(new URL('../', import.meta.url));
const source = fs.readFileSync(path.join(root, 'index.html'), 'utf8').replace(/\r\n/g, '\n');
const main = '<script type="module" src="./src/main.js"></script>';
assert.equal(source.split(main).length, 2, 'one landing-page main script required');
assert.equal(source.split('<head>').length, 2, 'one head required');
const output = source
  .replace(/(<script type="importmap">)([^]*?)(<\/script>)/, (_, start, json, end) => {
    const map = JSON.parse(json);
    // The adapter imports the original modules outside this importer scope.
    // Other builders, game pages and bake closures are unchanged.
    map.scopes = { ...map.scopes, './src/main.js': {
      ...map.scopes?.['./src/main.js'],
      ...Object.fromEntries(['batch2', 'spatial', 'fixture-cells', 'compact-static', 'ndproxy']
        .map(name => ['./src/core/' + name + '.js', './src/core/loading-finalize-diagnostics.js'])),
    } };
    return start + '\n' + JSON.stringify(map, null, 2) + '\n' + end;
  })
  .replace(/<!-- GENERATED[^]*?-->/, '<!-- GENERATED by tools/gen-loading-diagnostics.mjs from index.html. Do not edit. -->')
  .replace('<head>', `<head>\n<meta name="diagnostics-version" content="${VERSION}">\n<script src="./src/core/loading-diagnostics.js"></script>`)
  .replace(/<title>[^]*?<\/title>/, '<title>Loading diagnostics · Saint Petersburg</title>')
  .replace(main, '<script id="diagnostic-main" type="text/plain" data-src="./src/main.js"></script>');
const target = path.join(root, 'diagnostics.html');
if (process.argv.includes('--check')) {
  assert.equal(fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n'), output,
    'diagnostics.html is stale: run node tools/gen-loading-diagnostics.mjs');
  console.log('diagnostics.html matches the current landing page');
} else {
  fs.writeFileSync(target, output);
  console.log('Generated diagnostics.html');
}
