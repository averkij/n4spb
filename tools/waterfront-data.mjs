// Generate bounded visual-only waterfront coverage, using the existing city's
// surveyed footprints. Never import the full source scene into a runtime page.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath,pathToFileURL} from 'node:url';
import {execFileSync} from 'node:child_process';
import {REGISTRY} from '../src/areas/registry.js';
import {selectWaterfront,shoreSegments,BANK_DEPTH,VIEW_REACH} from './lib/waterfront-selection.mjs';
import {CONTEXT as KRONVERK_WATER} from '../src/areas/kronverk/water-context.js';
import {CONTEXT as APTEKARSKY_WATER} from '../src/areas/aptekarsky/water-context.js';
import {CONTEXT as ISLANDS_WATER} from '../src/areas/islands/water-context.js';
import {RIVERFRONT_SOURCES} from './lib/riverfront-groups.mjs';
import {rectDistance,hasWaterfront} from './lib/waterfront-selection.mjs';

const root=fileURLToPath(new URL('../',import.meta.url));
const source=path.resolve('D:/git2/agi-fun-tests/102_3d_piter/src/world/data');
const sourceData=await import(pathToFileURL(path.join(source,'city.js')).href);
const rows=Object.values(REGISTRY).filter(r=>!r.parked&&r.status!=='planned');
const local=new Map(),all=new Map(sourceData.BUILDINGS.map(b=>[b.id,b])),overlaps=new Map(),known={};
for(const q of sourceData.OVERLAPS)overlaps.set(q.a+'|'+q.b,q);
for(const row of rows){
  const file=path.join(root,row.remap['src/world/data/city.js']);
  const data=await import(pathToFileURL(file).href); local.set(row.id,{file,data});
  const knownFile=row.remap['src/world/city/known-data.js'];
  if(knownFile)Object.assign(known,(await import(pathToFileURL(path.join(root,knownFile)).href)).KNOWN_DATA);
  for(const b of data.BUILDINGS)if(!b.waterfront)all.set(b.id,b);
  for(const q of data.OVERLAPS)overlaps.set(q.a+'|'+q.b,q);
}
// The source has no polygon for Malaya Neva / Malaya Nevka. Use the current
// authored water context for those real shorelines, not an estimated offset
// from the old source's centreline. Gulf scenery is deliberately excluded.
const extraRings=new Map([...KRONVERK_WATER,...APTEKARSKY_WATER,...ISLANDS_WATER].filter(r=>r.key==='neva'&&r.id!=='gulf-0').map(r=>[r.id,r.ring]));
const branches=[...extraRings.values()].map(ring=>({id:'r1114249',polys:[{o:ring,h:[]}]}));
const buildings=[...all.values()],segments=shoreSegments([...sourceData.RIVER,...branches]);
const sourceCommit=execFileSync('git',['-C',source,'rev-parse','HEAD'],{encoding:'utf8'}).trim();
const dry=process.argv.includes('--dry'), only=process.argv.indexOf('--area');
for(const row of rows){
  if(only>=0&&row.id!==process.argv[only+1])continue;
  const {file,data}=local.get(row.id),existing=data.BUILDINGS.filter(b=>!b.waterfront);
  const areaFile=path.join(root,row.remap['src/world/area.js']);
  let areaText=fs.readFileSync(areaFile,'utf8').replace(/\n\/\/ BEGIN WATERFRONT[\s\S]*?\/\/ END WATERFRONT\n?/g,'').replace(/^[ \t]*["']landmarksRiverfront["'],?[ \t]*\r?\n/gm,'');
  const groups=[];
  if(hasWaterfront(row.play,segments))for(const [module,sourceGroups]of RIVERFRONT_SOURCES){
    if(new RegExp(`["']${module}["']`).test(areaText))continue;
    if(!sourceGroups.some(g=>rectDistance(row.play,...g.at)<=VIEW_REACH))continue;
    for(const g of sourceGroups)groups.push({...g,key:'riverfront-'+g.key,osm:[],sourceModule:module});
  }
  const landmarkIds=new Set(groups.flatMap(g=>g.ids)),have=new Set(existing.map(b=>b.id));
  const byId=new Map(selectWaterfront({buildings,existing,play:row.play,segments}).map(b=>[b.id,b]));
  for(const b of buildings)if(!have.has(b.id)&&(landmarkIds.has(b.id)||landmarkIds.has(b.parent)))byId.set(b.id,{...b,waterfront:true});
  const extra=[...byId.values()];
  const ids=new Set([...existing,...extra].map(b=>b.id)),extraIds=new Set(extra.map(b=>b.id));
  const joined=[...overlaps.values()].filter(q=>ids.has(q.a)&&ids.has(q.b)&&(extraIds.has(q.a)||extraIds.has(q.b)));
  const specs=Object.fromEntries([...ids].filter(id=>extraIds.has(id)&&known[id]).map(id=>[id,known[id]]));
  const text=`// GENERATED by node tools/waterfront-data.mjs. OpenStreetMap contributors, ODbL.\n// Source 102_3d_piter ${sourceCommit}, supplemented by current live area records.\n// Visual waterfront only: ${BANK_DEPTH}m bank depth, ${VIEW_REACH}m view reach; complete landmark families retain their roofs. PLAY, EXTENT, roads, gates are unchanged.\nexport const BUILDINGS = ${JSON.stringify(extra)};\nexport const OVERLAPS = ${JSON.stringify(joined)};\nexport const KNOWN_DATA = ${JSON.stringify(specs)};\nexport const GROUPS = ${JSON.stringify(groups)};\n`;
  console.log(`${row.id}: +${extra.length} records (${extra.filter(b=>!b.skip&&!b.dupOf).length} visible), ${(Buffer.byteLength(text)/1024).toFixed(0)} KiB`);
  if(dry)continue;
  fs.writeFileSync(path.join(path.dirname(file),'waterfront.js'),text);
  let facade=fs.readFileSync(file,'utf8').replace(/^import \* as WF from '\.\/waterfront\.js';\r?\n/m,'');
  facade=facade.replace(/^import \* as P0 /m,"import * as WF from './waterfront.js';\nimport * as P0 ");
  for(const name of ['BUILDINGS','OVERLAPS']){
    facade=facade.replaceAll(`.concat(WF.${name})`,'');
    facade=facade.replace(new RegExp(`^(export const ${name} = .+);$`,'m'),`$1.concat(WF.${name});`);
  }
  fs.writeFileSync(file,facade);
  if(groups.length){
    areaText=areaText.replace(/(export const MODULES = \[)\s*/,'$1\n  "landmarksRiverfront",\n  ');
    areaText+=`\n// BEGIN WATERFRONT - regenerated by tools/waterfront-data.mjs\nimport { GROUPS as RIVERFRONT_GROUPS } from './data/waterfront.js';\nGROUPS.landmarksRiverfront = RIVERFRONT_GROUPS;\n// END WATERFRONT\n`;
  }
  fs.writeFileSync(areaFile,areaText);
  const knownFile=row.remap['src/world/city/known-data.js'];
  if(knownFile){
    const p=path.join(root,knownFile),original=fs.readFileSync(p,'utf8').replace(/\n\/\/ BEGIN WATERFRONT[\s\S]*?\/\/ END WATERFRONT\n?/g,'');
    fs.writeFileSync(p,original+`\n// BEGIN WATERFRONT - regenerated by tools/waterfront-data.mjs\nimport { KNOWN_DATA as WATERFRONT_KNOWN } from './data/waterfront.js';\nObject.assign(KNOWN_DATA, WATERFRONT_KNOWN);\n// END WATERFRONT\n`);
  }
}
