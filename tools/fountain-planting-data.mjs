// Regenerate pure per-area planting masks after fountain data changes.
// node tools/fountain-planting-data.mjs --area vasilyevsky [--check]
// Repeat --area for several areas. Does not import area/layout/world modules.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath,pathToFileURL } from 'node:url';
import { REGISTRY } from '../src/areas/registry.js';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const argv=process.argv.slice(2),areas=argv.flatMap((arg,i)=>arg==='--area'?[argv[i+1]]:[]),check=argv.includes('--check');
if(!areas.length)throw new Error('usage: node tools/fountain-planting-data.mjs --area <id> [--check]');
for(const area of areas){
  const row=REGISTRY[area];if(!row||row.parked||row.status==='planned')throw new Error(`not a live area: ${area}`);
  const city=await import(pathToFileURL(path.join(root,row.remap['src/world/data/city.js'])).href),sites=new Map();
  for(const f of[...city.FOUNTAINS,...city.WATER.filter(w=>w.kind==='fountain')]){
    const old=sites.get(f.id);sites.set(f.id,{id:f.id,x:f.x??old?.x,z:f.z??old?.z,polys:f.polys?.length?f.polys:old?.polys||[]});
  }
  const file=path.join(root,'src/areas',area,'fountain-rings.js');
  const source=`// Generated by node tools/fountain-planting-data.mjs --area ${area}.\n// Exact mapped fountain footprints and dry holes; pure area data avoids\n// a data-facade/layout import cycle. Do not hand-edit; regenerate and check.\nexport const FOUNTAIN_SITES = ${JSON.stringify([...sites.values()])};\n`;
  if(check){if(!fs.existsSync(file)||fs.readFileSync(file,'utf8')!==source)throw new Error(`${area}: fountain planting data is stale; regenerate`);}
  else fs.writeFileSync(file,source);
  console.log(`Fountain planting ${check?'CHECK':'WRITE'} ${area}: ${sites.size} exact source sites.`);
}
