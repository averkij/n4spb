// CPU test of the generated src/core/baked-revision.js (tools/lib/revision-module.mjs): the rendered module is imported with a fake `document` for each area and must give BAKED_REVISION === map[area];
// an unknown or parked area, and no document at all (Node tools), give 'none', which never matches a manifest. Also the shape: sorted, one entry per line, parse(render(map)) === map, bad input refused.
//   node tools/baked-revision-js-test.mjs
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';
import { pathToFileURL } from 'node:url';
import { renderRevisionModule, parseRevisionModule } from './lib/revision-module.mjs';

const MAP = { vasilyevsky: '5'.repeat(20), admiralty: '1'.repeat(20), smolny: '3'.repeat(20), palace: '2'.repeat(20), vladimirsky: '4'.repeat(20) };
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'n4spb-revjs-'));
let n = 0, bad = 0, serial = 0;
const test = async (name, fn) => { n++; try { await fn(); console.log(`ok   ${name}`); } catch (e) { bad++; console.log(`FAIL ${name}\n     ${String(e.message).split('\n').slice(0, 6).join('\n     ')}`); } };
/** import the module text under a fake document ({ dataset.area } or none) */
async function load(text, area, { document = true } = {}) {
  const f = path.join(dir, `rev${++serial}.mjs`); fs.writeFileSync(f, text);
  const had = Object.getOwnPropertyDescriptor(globalThis, 'document');
  if (document) globalThis.document = { documentElement: { dataset: area === undefined ? {} : { area } } }; else delete globalThis.document;
  try { return await import(pathToFileURL(f).href); }
  finally { if (had) Object.defineProperty(globalThis, 'document', had); else delete globalThis.document; }
}
try {
  const text = renderRevisionModule(MAP);
  await test('the shape: header, alphabetical one-per-line entries, a trailing newline', () => {
    const lines = text.split('\n');
    assert.equal(lines[0], '// Generated by tools/lib/bake-publish.mjs / tools/baked-revision-sync.mjs. Do not edit. One bake revision per live area.');
    assert.equal(lines[1], 'export const BAKED_REVISIONS = {');
    assert.deepEqual(lines.slice(2, 7), ["  admiralty: '" + '1'.repeat(20) + "',", "  palace: '" + '2'.repeat(20) + "',", "  smolny: '" + '3'.repeat(20) + "',", "  vasilyevsky: '" + '5'.repeat(20) + "',", "  vladimirsky: '" + '4'.repeat(20) + "',"].sort((a, b) => (a < b ? -1 : 1)));
    assert(text.endsWith('\n') && !text.endsWith('\n\n'));
    assert.equal(renderRevisionModule({ ...MAP }), text, 'insertion order is irrelevant');
  });
  await test('parse(render(map)) is the map; any other text does not parse', () => {
    assert.deepEqual(parseRevisionModule(text), MAP);
    assert.deepEqual(parseRevisionModule(renderRevisionModule({})), {});
    assert.equal(parseRevisionModule("// Generated by npm run bake.\nexport const BAKED_REVISION = '78fc35d9a53453f9fa9a';\n"), null, 'the legacy constant');
    assert.equal(parseRevisionModule(text.replace("'1'", "'zz'").replace('1'.repeat(20), 'g'.repeat(20))), null, 'a non-hex revision');
    assert.equal(parseRevisionModule(text.replace("  palace:", "  admiralty: '" + '9'.repeat(20) + "',\n  palace:")), null, 'a duplicate key');
  });
  await test('bad input is refused: an id that is not a name, a revision that is not 20 hex digits', () => {
    assert.throws(() => renderRevisionModule({ 'a b': '1'.repeat(20) }), /bad area id/);
    assert.throws(() => renderRevisionModule({ x: 'abc' }), /20 hex digits/);
    assert.throws(() => renderRevisionModule({ x: undefined }), /20 hex digits/);
    assert.throws(() => renderRevisionModule({ x: '1'.repeat(20).toUpperCase().replace(/1/g, 'A') }), /20 hex digits/);
  });
  for (const [area, rev] of Object.entries(MAP)) {
    await test(`${area}: BAKED_REVISION === its entry and BAKED_REVISIONS is the map`, async () => {
      const m = await load(text, area);
      assert.equal(m.BAKED_REVISION, rev); assert.deepEqual({ ...m.BAKED_REVISIONS }, MAP);
    });
  }
  await test("an unknown area, a parked area, an empty data-area and no document give 'none'", async () => {
    assert.equal((await load(text, 'strip')).BAKED_REVISION, 'none');
    assert.equal((await load(text, 'nowhere')).BAKED_REVISION, 'none');
    assert.equal((await load(text, undefined)).BAKED_REVISION, 'none', 'no data-area');
    assert.equal((await load(text, '')).BAKED_REVISION, 'none');
    const m = await load(text, 'palace', { document: false });
    assert.equal(m.BAKED_REVISION, 'none', 'Node tools have no document');
    assert.deepEqual({ ...m.BAKED_REVISIONS }, MAP, 'the map itself is always there');
  });
  await test('the module has no other exports (the loader and gates read only these two)', async () => {
    assert.deepEqual(Object.keys(await load(text, 'palace')).sort(), ['BAKED_REVISION', 'BAKED_REVISIONS']);
  });
} finally { fs.rmSync(dir, { recursive: true, force: true }); }
if (bad) { console.log(`RESULT: FAIL (${bad} of ${n})`); process.exit(1); }
console.log(`RESULT: OK (${n} checks)`);
