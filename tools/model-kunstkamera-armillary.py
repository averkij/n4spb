"""Build the 1993 Kunstkamera armillary in Blender, in metres.

Run blender -b -P tools/model-kunstkamera-armillary.py. Reference photographs
and the manufacturer's diameter are in docs/research/vasilyevsky-winter.md.
"""
from pathlib import Path
from math import cos, sin, tau, radians

import bpy
import bmesh
from mathutils import Quaternion, Vector


parts = {}


def mesh(material, name, vertices, faces):
    data = bpy.data.meshes.new(name)
    data.from_pydata(vertices, [], faces)
    bm = bmesh.new()
    bm.from_mesh(data)
    bmesh.ops.recalc_face_normals(bm, faces=list(bm.faces))
    bmesh.ops.triangulate(bm, faces=list(bm.faces))
    bm.to_mesh(data)
    bm.free()
    parts.setdefault(material, []).append(data)


def band(name, radius, width, angle, axis, offset=0, material="gold", thickness=0.012):
    q = Quaternion(Vector(axis), radians(angle))
    n = 40
    vertices = []
    faces = []
    for i in range(n):
        a = tau*i/n
        for r, h in [(radius,-width/2),(radius,width/2),(radius-thickness,width/2),(radius-thickness,-width/2)]:
            vertices.append(q @ Vector((r*cos(a),r*sin(a),h+offset)))
        j = (i+1) % n
        for k in range(4):
            faces.append((4*i+k,4*j+k,4*j+(k+1)%4,4*i+(k+1)%4))
    mesh(material, name, vertices, faces)


def turned(name, profile, segments, material):
    vertices = [(r*cos(tau*i/segments),r*sin(tau*i/segments),z)
                for r,z in profile for i in range(segments)]
    faces = [(k*segments+i,k*segments+(i+1)%segments,(k+1)*segments+(i+1)%segments,(k+1)*segments+i)
             for k in range(len(profile)-1) for i in range(segments)]
    faces.extend([tuple(range(segments)), tuple(range(len(vertices)-segments,len(vertices)))])
    mesh(material,name,vertices,faces)


# The wide titanium ecliptic carries twelve dark astronomical signs. Blender's
# text outlines are flattened against the band. The model uses local roof
# orientation, with Z up and the polar axis distinct from the pillar.
band("Meridian", .750, .073, 90, (1,0,0))
band("Horizon", .718, .045, 0, (1,0,0))
band("Inner meridian", .696, .040, 64, (0,1,0))
band("Equator", .694, .034, -29, (1,0,0))
for h in (-.271,.271):
    band("Tropic", .631, .030, -29, (1,0,0), h)
band("Zodiac", .739, .135, 38, (1,0,0), material="silver")
for edge in (-.067,.067):
    band("Folded zodiac edge", .746, .012, 38, (1,0,0), edge)
turned("Terrestrial globe",[(.018,-.122),(.076,-.095),(.113,-.045),(.123,0),
                           (.113,.045),(.076,.095),(.018,.122)],16,"gold")
turned("Polar spindle",[(.015,-.73),(.018,-.70),(.012,.70),(.019,.73)],8,"gold")
turned("Mounting ball",[(.04,-.94),(.109,-.90),(.128,-.84),(.107,-.78),(.05,-.74)],
       12,"iron")

# A typeface with open license and all twelve signs, bundled with Blender.
fontpath = Path(bpy.utils.system_resource('DATAFILES')) / "fonts" / "NotoSansSymbols-VariableFont_wght.woff2"
font = bpy.data.fonts.load(str(fontpath))
tilt = Quaternion(Vector((1,0,0)), radians(38))
for i in range(12):
    letter = bpy.data.curves.new("Zodiac sign", "FONT")
    letter.font = font
    letter.body = chr(0x2648+i)
    letter.resolution_u = 2
    ob = bpy.data.objects.new("Zodiac sign", letter)
    bpy.context.scene.collection.objects.link(ob)
    eva = ob.evaluated_get(bpy.context.evaluated_depsgraph_get())
    glyph = eva.to_mesh()
    xs = [v.co.x for v in glyph.vertices]
    ys = [v.co.y for v in glyph.vertices]
    if not xs or max(ys) == min(ys):
        raise RuntimeError("The Blender font must include the zodiac symbols")
    scale = .089 / (max(ys)-min(ys))
    coords = []
    for v in glyph.vertices:
        a = tau*i/12 - (v.co.x - (max(xs)+min(xs))/2)*scale/.741
        z = (v.co.y - (max(ys)+min(ys))/2)*scale
        coords.append(tilt @ Vector((.741*cos(a),.741*sin(a),z)))
    mesh("iron", "Enamel zodiac sign", coords, [list(reversed(p.vertices[:])) for p in glyph.polygons])
    eva.to_mesh_clear()
    bpy.data.objects.remove(ob, do_unlink=True)
    bpy.data.curves.remove(letter)

out = Path(__file__).resolve().parents[1]/"src/world/landmarksUniversity/armillary-model.js"
lines = ["// Generated by tools/model-kunstkamera-armillary.py. Positions in millimetres, Y up.",
         "import * as THREE from 'three';","","const parts = {"]
for material, geometries in parts.items():
    positions, indices = [], []
    for g in geometries:
        start = len(positions)//3
        for v in g.vertices:
            x,y,z = v.co
            positions.extend(round(1000*c) for c in (x,z,-y))
        indices.extend(start+i for p in g.polygons for i in p.vertices)
        bpy.data.meshes.remove(g)
    lines.append("  "+material+": [")
    for values in [positions,indices]:
        lines.append("    [")
        lines.extend("      "+",".join(map(str,values[i:i+30]))+"," for i in range(0,len(values),30))
        lines.append("    ],")
    lines.append("  ],")
    print(material,len(positions)//3,"vertices",len(indices)//3,"triangles")
lines += ["};", "", "export function armillaryGeometry(part) {",
          "  const [positions, indices] = parts[part];",
          "  const g = new THREE.BufferGeometry();",
          "  g.setAttribute('position', new THREE.Float32BufferAttribute(positions, 3));",
          "  g.scale(0.001, 0.001, 0.001);", "  g.setIndex(indices);",
          "  g.computeVertexNormals();", "  return g;", "}", ""]
out.write_text("\n".join(lines),encoding="utf-8",newline="\n")
