// CPU test of the one-shot migration tools/bake-migrate-closure.mjs on a fabricated git repository (two live areas, legacy bakes under the global revision): the rename is a pure rename (git sees 100% renames),
// the bytes are unchanged, the result passes the real check, and every broken precondition aborts BEFORE anything is changed. No GPU, no browser, no node_modules; needs git.
//   node tools/bake-migrate-test.mjs
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import zlib from 'node:zlib';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { migrate, countInGzip } from './bake-migrate-closure.mjs';
import { legacyGlobal } from './lib/legacy-revision.mjs';
import { checkBakes } from './bake-manifest-check.mjs';
import { makeRoot, writeTree, readJSON, KEYS } from './lib/bake-fixture.mjs';

let n = 0, bad = 0;
const test = async (name, fn) => { n++; try { await fn(); console.log(`ok   ${name}`); } catch (e) { bad++; console.log(`FAIL ${name}\n     ${String(e.stack || e.message).split('\n').slice(0, 8).join('\n     ')}`); } };
const git = (root, ...a) => { const r = spawnSync('git', a, { cwd: root, encoding: 'utf8' }); if (r.status !== 0) throw new Error(`git ${a.join(' ')}: ${r.stderr}`); return r.stdout; };
if (spawnSync('git', ['--version']).status !== 0) { console.log('git is not available: skipped'); process.exit(0); }

/** a legacy repository: bakes named with the global revision, the single-constant baked-revision.js, committed */
function legacyRepo({ poison = false } = {}) {
  const t = makeRoot(), L = legacyGlobal(t.root);
  // the legacy global covers src/**/*.js except baked-revision.js, so writing the constant does not change it
  writeTree(t.root, { 'src/core/baked-revision.js': `// Generated by npm run bake.\nexport const BAKED_REVISION = '${L}';\n` });
  for (const id of ['alpha', 'beta']) {
    const dir = path.join(t.root, 'assets', 'baked', id); fs.mkdirSync(dir, { recursive: true });
    const files = {}, sizes = {};
    for (const k of KEYS) {
      let raw = crypto.randomBytes(300 + k.length * 11);
      if (poison && id === 'beta' && k === 'roof') raw = Buffer.concat([raw, Buffer.from(`xx${L}yy`), raw]);
      const gz = zlib.gzipSync(raw), name = `${k}.${L}.bin.gz`; fs.writeFileSync(path.join(dir, name), gz); files[k] = name; sizes[k] = { raw: raw.length, gzip: gz.length };
    }
    fs.writeFileSync(path.join(dir, 'manifest.json'), JSON.stringify({ format: 1, area: id, revision: L, files, sizes }, null, 2));
  }
  git(t.root, 'init', '-q'); git(t.root, 'config', 'user.email', 't@t'); git(t.root, 'config', 'user.name', 't'); git(t.root, 'config', 'core.autocrlf', 'false');
  git(t.root, 'add', '-A'); git(t.root, 'commit', '-q', '-m', 'legacy');
  return { ...t, L };
}
const quiet = { log: () => {} };
const sha = (f) => crypto.createHash('sha256').update(fs.readFileSync(f)).digest('hex');

await test('countInGzip: finds the needle across chunk boundaries, counts every hit, finds nothing in clean data', async () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'mig-')), needle = '78fc35d9a53453f9fa9a';
  try {
    const noise = () => crypto.randomBytes(1 << 20);
    const cases = { none: noise(), start: Buffer.concat([Buffer.from(needle), noise()]), end: Buffer.concat([noise(), Buffer.from(needle)]), mid: Buffer.concat([noise(), Buffer.from(needle), noise()]), two: Buffer.concat([Buffer.from(needle), noise(), Buffer.from(needle)]) };
    const want = { none: 0, start: 1, end: 1, mid: 1, two: 2 };
    for (const [k, buf] of Object.entries(cases)) { const f = path.join(dir, `${k}.gz`); fs.writeFileSync(f, zlib.gzipSync(buf)); assert.equal(await countInGzip(f, needle), want[k], k); }
    // the needle straddling the edges of the 16 KiB / 64 KiB chunks of the decompressor
    for (const off of [16384 - 19, 16384 - 10, 16384 - 1, 65536 - 19, 65536 - 10, 65536 - 1, 65536, 131072 - 7]) {
      const b = Buffer.alloc(200000, 0x41); Buffer.from(needle).copy(b, off); const f = path.join(dir, `x${off}.gz`); fs.writeFileSync(f, zlib.gzipSync(b)); assert.equal(await countInGzip(f, needle), 1, `offset ${off}`);
    }
  } finally { fs.rmSync(dir, { recursive: true, force: true }); }
});

await test('the migration: pure renames (git: 100%), same bytes, new manifests, generated map, the real check is green', async () => {
  const t = legacyRepo();
  try {
    const before = {};
    for (const id of ['alpha', 'beta']) for (const k of KEYS) before[`${id}/${k}`] = sha(path.join(t.root, 'assets/baked', id, `${k}.${t.L}.bin.gz`));
    const r = await migrate(t.root, quiet);
    assert.equal(r.renamed, KEYS.length * 2);
    const revs = Object.fromEntries(['alpha', 'beta'].map((id) => [id, readJSON(path.join(t.root, 'assets/baked', id, 'manifest.json')).revision]));
    assert.notEqual(revs.alpha, revs.beta); assert.ok(!Object.values(revs).includes(t.L));
    for (const id of ['alpha', 'beta']) {
      const m = readJSON(path.join(t.root, 'assets/baked', id, 'manifest.json'));
      assert.equal(m.scheme, 2); assert.equal(m.area, id); assert.ok(m.closure.files > 0);
      for (const k of KEYS) { assert.equal(m.files[k], `${k}.${revs[id]}.bin.gz`); assert.equal(m.sha256[k], before[`${id}/${k}`], 'sha256 = the bytes before the rename'); }
      assert.ok(fs.existsSync(path.join(t.root, 'assets/baked', id, 'inputs.json')));
      assert.deepEqual(fs.readdirSync(path.join(t.root, 'assets/baked', id)).filter((f) => f.endsWith('.bin.gz')).sort(), Object.values(m.files).sort(), 'no old product left');
    }
    git(t.root, 'add', '-A');
    const sum = git(t.root, 'diff', '--cached', '-M', '--summary');
    const renames = sum.split('\n').filter((l) => /rename .*\(100%\)/.test(l));
    assert.equal(renames.length, KEYS.length * 2, `100% renames\n${sum.slice(0, 600)}`);
    assert.ok(!/create mode .*bin\.gz/.test(sum), 'no new product blob');
    const res = checkBakes(t.root, {});
    assert.equal(res.ok, true, res.lines.join(' | '));
  } finally { t.remove(); }
});

await test('a dry run changes nothing', async () => {
  const t = legacyRepo();
  try { const r = await migrate(t.root, { dryRun: true, ...quiet }); assert.equal(r.dryRun, true); assert.equal(git(t.root, 'status', '--porcelain').trim(), ''); } finally { t.remove(); }
});

await test('refused and nothing changed: a dirty tree, a tree that is not the baked tree, a product the manifest does not list, a product that embeds the old revision, an already migrated tree', async () => {
  let t = legacyRepo();
  try {
    fs.appendFileSync(path.join(t.root, 'src/core/engine.js'), '// edit\n');
    await assert.rejects(() => migrate(t.root, quiet), /not clean/);
    git(t.root, 'commit', '-qam', 'edit');
    await assert.rejects(() => migrate(t.root, quiet), /not the baked tree/);
    git(t.root, 'checkout', '-q', 'HEAD~1', '--', 'src/core/engine.js'); git(t.root, 'commit', '-qam', 'undo');
    fs.writeFileSync(path.join(t.root, 'assets/baked/alpha', `stray.${t.L}.bin.gz`), 'x'); git(t.root, 'add', '-A'); git(t.root, 'commit', '-qm', 'stray');
    await assert.rejects(() => migrate(t.root, quiet), /does not list/);
    assert.equal(git(t.root, 'status', '--porcelain').trim(), '', 'nothing changed by the refusals');
  } finally { t.remove(); }
  t = legacyRepo({ poison: true });
  try {
    await assert.rejects(() => migrate(t.root, quiet), /contains the old revision/);
    assert.equal(git(t.root, 'status', '--porcelain').trim(), '', 'the scan runs before any rename');
  } finally { t.remove(); }
  t = legacyRepo();
  try { await migrate(t.root, quiet); git(t.root, 'add', '-A'); git(t.root, 'commit', '-qm', 'migrated'); await assert.rejects(() => migrate(t.root, quiet), /legacy single constant/); } finally { t.remove(); }
});

console.log(`bake-migrate-test: ${n - bad} passed, ${bad} failed`);
console.log(bad ? 'RESULT: FAIL' : 'RESULT: OK');
process.exit(bad ? 1 : 0);
