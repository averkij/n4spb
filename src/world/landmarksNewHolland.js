export const OWNS_GROUPS = true;

import * as THREE from 'three';
import { Parts } from './landmarksNewHolland/kit.js';
import { makeMats } from './landmarksNewHolland/mats.js';

const PARTS = [
  ['arch', () => import('./landmarksNewHolland/arch.js')],
  ['warehouses', () => import('./landmarksNewHolland/warehouses.js')],
  ['bottle', () => import('./landmarksNewHolland/bottle.js')],
  ['buildings', () => import('./landmarksNewHolland/buildings.js')],
  ['water', () => import('./landmarksNewHolland/water.js')],
  ['park', () => import('./landmarksNewHolland/park.js')],
];

export async function build(ctx) {
  const t0 = performance.now();
  const M = makeMats(ctx);
  const root = new THREE.Group(); root.name = 'landmarksNewHolland';
  const svc = { monuments: [], photoSpots: [], entrances: [], crowd: [], benches: [], fences: [], bridges: [], triangles: 0, parts: {} };
  const failed = [];
  for (const [name, load] of PARTS) {
    const t1 = performance.now();
    const K = { ctx, M, THREE, P: new Parts(), svc, root, extraTris: 0 };
    try {
      const m = await load();
      await m.build(K);
    } catch (e) { console.error(`[landmarksNewHolland] ${name} failed:`, e); failed.push(`${name}: ${e && e.stack || e}`); }
    for (const k of K.P.b.values()) { const bad = k.pos.findIndex((v) => !Number.isFinite(v)); if (bad >= 0) console.warn(`[landmarksNewHolland] ${name}: NaN vertex in ${k.mat.name} at ${bad / 3 | 0}`); }
    if (typeof process !== 'undefined' && process.env && process.env.NH_BOX) for (const k of K.P.b.values()) { let a = [1e9, 1e9, 1e9], b = [-1e9, -1e9, -1e9]; for (let i = 0; i < k.pos.length; i += 3) for (let j = 0; j < 3; j++) { a[j] = Math.min(a[j], k.pos[i + j]); b[j] = Math.max(b[j], k.pos[i + j]); } console.log('[NH_BOX]', name, k.mat.name, 'tris', k.idx.length / 3 | 0, 'min', a.map((v) => v.toFixed(0)).join(','), 'max', b.map((v) => v.toFixed(0)).join(',')); }
    const tris = K.P.tris + K.extraTris;
    const meshes = K.P.build(root, { name });
    for (const m of meshes) if (M.cutouts.has(m.material) || M.decals.has(m.material)) ctx.noOutline(m);
    svc.triangles += tris; svc.parts[name] = { tris, ms: Math.round(performance.now() - t1) };
  }
  ctx.addStatic(root);
  const S = (ctx.services.landmarks ||= {});
  S.monuments = (S.monuments || []).concat(svc.monuments);
  S.photoSpots = (S.photoSpots || []).concat(svc.photoSpots);
  ctx.services.landmarksNewHolland = { ...svc, buildMs: Math.round(performance.now() - t0) };
  if (typeof process !== 'undefined' && process.env && process.env.NH_DEBUG) console.log('[landmarksNewHolland] parts', JSON.stringify(svc.parts), JSON.stringify(svc.warehouseStats || {}), JSON.stringify(svc.trees || {}), JSON.stringify(svc.park || {}), svc.waterMode, 'tris', svc.triangles);
  if (failed.length) throw new Error('landmarksNewHolland parts failed:\n' + failed.join('\n'));
}
